function hoSenOutline(floor, code) {
  for (const [codes, edges] of lowerRows[floor]) {
    const index = codes.split(' ').indexOf(code);
    if (index >= 0) return rectangle(edges[index], 809, edges[index + 1], 890);
  }
  for (const [column, codes] of (rightRooms[floor] || []).entries()) {
    const index = codes.split(' ').indexOf(code);
    const edges = [351, 437, 522, 606, 691];
    if (index >= 0) return rectangle(column ? 1676 : 1557, edges[index], column ? 1762 : 1649, edges[index + 1]);
  }
  const upperIndex = upperRooms[floor]?.split(' ').indexOf(code) ?? -1;
  if (upperIndex >= 0) {
    const [a, b] = upperEdges.slice(upperIndex, upperIndex + 2);
    const slope = (x) => 265 - (x - 155) * 0.108;
    return [[a, slope(a)], [b, slope(b)], [b + 7, slope(b) + 91], [a + 7, slope(a) + 91]];
  }
  const bounds = leftRooms[floor]?.[code];
  return bounds ? rectangle(...bounds) : hoSenSpecial[floor]?.[code];
}

export function hcmRoomArea(prefix, floor, code, width, height) {
  const points = prefix === 'nvh' ? nvhRooms[floor]?.[code] : hoSenOutline(floor, code);
  return points?.map(([x, y]) => `${(x * 100 / width).toFixed(2)},${(y * 100 / height).toFixed(2)}`).join(' ');
}
