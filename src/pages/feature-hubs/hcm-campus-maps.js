function floorPlans(prefix, building, width, height, floors) {
  const [left, top, right, bottom] = prefix === 'nvh' ? [96, 205, 1105, 1050] : [139, 124, 1782, 909];
  return Object.entries(floors).map(([floor, points]) => ({
    building, floor,
    crop: { left: 100 * left / width, top: 100 * top / height, right: 100 * right / width, bottom: 100 * bottom / height },
    imageHash: imageHashes[`${prefix}-${floor.toLowerCase()}`],
    imageUrl: images[`../../assets/campus-maps/hcm/${prefix}-${floor.toLowerCase()}.jpg`],
    rooms: points.map(([number, x, y, hall]) => {
      const code = prefix === 'nvh' ? `NVH-${number}` : number;
      const planArea = hcmRoomArea(prefix, floor, String(number), width, height);
      const sharedFloors = code === 'HT-A' ? ['5', '6'] : code === 'HT-B' ? ['5'] : [];
      return {
        code, name: hall || `Phòng ${code}`, type: hall ? 'Hội trường' : 'Phòng',
        planX: Math.round(100 * x / width), planY: Math.round(100 * y / height),
        planArea,
        planAreasByFloor: sharedFloors.length ? Object.fromEntries(sharedFloors.map((sharedFloor) => [sharedFloor, planArea])) : undefined,
        capacity: 0, isBookable: false,
      };
    }),
  }));
}

export const hcmCampusMaps = [
  ...floorPlans('ho-sen', 'Tòa Hồ Sen', 1920, 1080, hoSen).sort((a, b) => (a.floor === 'G' ? -1 : Number(a.floor)) - (b.floor === 'G' ? -1 : Number(b.floor))),
  ...floorPlans('nvh', 'Nhà Văn hóa', 1200, 1500, nvh),
];

export async function recognizeHcmPlan(file) {
  if (!globalThis.crypto?.subtle) return undefined;
  const bytes = new Uint8Array(await crypto.subtle.digest('SHA-256', await file.arrayBuffer()));
  const hash = Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('');
  return hcmCampusMaps.find((plan) => plan.imageHash === hash);
}
